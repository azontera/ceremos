// parsePack（src/lib/template-pack.ts）相当の簡易検証
// ---------------------------------------------------------------
function validatePack(pack) {
  if (!pack || typeof pack !== "object") return "JSONオブジェクトではありません";
  if (!pack.name || typeof pack.name !== "string") return "name（テンプレ名）がありません";
  const hasAny =
    (pack.quote?.items?.length ?? 0) > 0 ||
    (pack.rundown?.items?.length ?? 0) > 0 ||
    (pack.menu?.items?.length ?? 0) > 0;
  if (!hasAny) return "quote / menu / rundown のいずれも空です";
  for (const it of pack.quote?.items ?? []) if (!it.name) return "quote.items に name の無い行があります";
  for (const it of pack.rundown?.items ?? []) if (!it.title) return "rundown.items に title の無い行があります";
  for (const it of pack.menu?.items ?? []) if (!it.name) return "menu.items に name の無い行があります";
  // JSON化して壊れないことも確認
  try { JSON.parse(JSON.stringify(pack)); } catch { return "JSONにシリアライズできません"; }
  return null;
}

