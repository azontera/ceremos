const PACKS = [
  bridal01, bridal02, bridal03, bridal04, bridal05,
  bridal06, bridal07, bridal08, bridal09, bridal10,
  banquet11, banquet12, banquet13, banquet14, banquet15,
];

async function main() {
  console.log("🎁 初期テンプレート一式（15本）の投入を開始…");

  // 全パックを事前検証（1本でも不正なら中断）
  for (const pack of PACKS) {
    const err = validatePack(pack);
    if (err) throw new Error(`パック「${pack?.name ?? "(名称不明)"}」の検証エラー: ${err}`);
  }
  console.log(`  ✓ 全${PACKS.length}パックの検証OK（parsePack相当）`);

  let created = 0, updated = 0;
  for (const pack of PACKS) {
    const bodyJson = JSON.stringify(pack);
    const existing = await prisma.template.findFirst({ where: { type: "pack", name: pack.name } });
    if (existing) {
      await prisma.template.update({ where: { id: existing.id }, data: { bodyJson, isSystem: true } });
      updated++;
      console.log(`  ↻ 更新: ${pack.name}`);
    } else {
      await prisma.template.create({ data: { type: "pack", name: pack.name, bodyJson, isSystem: true } });
      created++;
      console.log(`  + 登録: ${pack.name}`);
    }
  }

  const total = await prisma.template.count({ where: { type: "pack" } });
  console.log(`\n完了 🎉 新規${created}件・更新${updated}件（今回処理: ${PACKS.length}件）`);
  console.log(`Template（type="pack"）の合計: ${total}件`);
}

main().catch((e) => { console.error(e); process.exit(1); }).finally(() => prisma.$disconnect());
