const FEEDS: Record<string, string> = { 木: "火", 火: "土", 土: "金", 金: "水", 水: "木" };
const FEED_TEXT: Record<string, string> = {
  "木火": "木は燃えて火を大きくする——おそばにいるだけで相手を輝かせる組み合わせ",
  "火土": "火は大地を温め土を肥やす——情熱が家庭のあたたかさに変わる組み合わせ",
  "土金": "土の中で金は磨かれ生まれる——堅実さが互いの価値を高める組み合わせ",
  "金水": "金は清らかな水を生む——品格と知性が響き合う組み合わせ",
  "水木": "水は木を育て大きくする——支え合いがそのまま成長になる組み合わせ",
};

export function elementsTrivia(a?: string, b?: string): string {
  const base = "四柱推命では、生まれ年の十干から「木・火・土・金・水」の五行を導きます。";
  if (!a || !b) return base;
  if (FEEDS[a] === b) return `${base}${a}と${b}は「相生（そうじょう）」——${FEED_TEXT[a + b] ?? "互いを生かし合う関係"}とされ、古来たいへん縁起の良い巡り合わせです。`;
  if (FEEDS[b] === a) return `${base}${b}と${a}は「相生（そうじょう）」——${FEED_TEXT[b + a] ?? "互いを生かし合う関係"}とされ、古来たいへん縁起の良い巡り合わせです。`;
  if (a === b) return `${base}おふたりは同じ「${a}」の気質。価値観の根っこが近く、言葉にしなくても通じ合う間柄といわれます。`;
  return `${base}異なる五行を持つおふたりは、互いに無いものを持ち寄る組み合わせ。違いこそが夫婦の財産になります。`;
}

/** 締めの文面：この結婚式・この式場との「縁」を寿ぐ */
export function enMusubi(venueName: string, weddingDate: Date, bridal: boolean): string[] {
  const dateStr = weddingDate.toLocaleDateString("ja-JP", { year: "numeric", month: "long", day: "numeric" });
  const venue = venueName || "この会場";
  if (!bridal) {
    return [
      `数ある会場の中から${venue}にたどり着かれたことも、ひとつのご縁。`,
      `${dateStr}の集いが、お集まりになる皆さまの記憶に永く残る一日となりますよう、スタッフ一同、心を尽くしてお手伝いいたします。`,
    ];
  }
  return [
    `袖振り合うも多生の縁——仏教では、道で袖が触れ合うほどの出会いにも、前世からの深い因縁があると説きます。`,
    `おふたりが出会い、同じ日を選び、数ある式場の中から${venue}の扉を開かれたこと。そのすべてが、偶然ではなく積み重なったご縁です。`,
    `${dateStr}。この一日が、おふたりの物語の最も美しい章のはじまりとなりますよう。${venue}もまた、おふたりとのご縁を胸に、心を尽くしてお手伝いいたします。`,
  ];
}

/** 相性スコアのひとこと格付け（点数の見せ方を楽しく） */
export function compatGrade(score: number): string {
  if (score >= 90) return "縁結びの神さまも太鼓判";
  if (score >= 80) return "たいへん良い巡り合わせ";
  if (score >= 70) return "支え合いで伸びるご縁";
  return "違いが宝物になるご縁";
}

